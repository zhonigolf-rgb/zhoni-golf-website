export function planCategoryIndex(id) {
  return { T: 0, C: 1, P: 2, M: 3 }[id[0]];
}

export function resolveInquiryPlan(params, fallback = "", locale = "en") {
  const id = params.get("plan");
  const copy = productPlanCopy[locale];
  if (!id || !copy?.plans[id]) return fallback;
  return `${copy.category[planCategoryIndex(id)]} — ${id}: ${copy.plans[id][0]}`.slice(0, 140);
}
